import 'dart:convert';
import 'dart:typed_data';

import 'package:dio/dio.dart';

import '../thingsboard_client_base.dart';
import '../http/http_utils.dart';
import '../model/model.dart';

PageData<GeneratedReport> parseGeneratedReportPageData(
    Map<String, dynamic> json) {
  return PageData.fromJson(json, (json) => GeneratedReport.fromJson(json));
}

PageData<ReportTemplateInfo> parseReportTemplateInfoPageData(
    Map<String, dynamic> json) {
  return PageData.fromJson(json, (json) => ReportTemplateInfo.fromJson(json));
}

class ReportService {
  final ThingsboardClient _tbClient;

  factory ReportService(ThingsboardClient tbClient) {
    return ReportService._internal(tbClient);
  }

  ReportService._internal(this._tbClient);

  Future<ResponseBody?> downloadDashboardReport(
      String dashboardId, ReportParams reportParams,
      {RequestConfig? requestConfig}) async {
    var options = defaultHttpOptionsFromConfig(requestConfig);
    options.responseType = ResponseType.stream;
    var response = await _tbClient.post<ResponseBody>(
        '/api/report/$dashboardId/download',
        data: jsonEncode(reportParams),
        options: options);
    return response.data;
  }

  Future<ResponseBody?> downloadTestReport(ReportConfig reportConfig,
      {String? reportsServerEndpointUrl, RequestConfig? requestConfig}) async {
    var queryParams = <String, dynamic>{};
    if (reportsServerEndpointUrl != null) {
      queryParams['reportsServerEndpointUrl'] = reportsServerEndpointUrl;
    }
    var options = defaultHttpOptionsFromConfig(requestConfig);
    options.responseType = ResponseType.stream;
    var response = await _tbClient.post<ResponseBody>('/api/report/test',
        queryParameters: queryParams,
        data: jsonEncode(reportConfig),
        options: options);
    return response.data;
  }

  // ---------------------------------------------------------------------------
  // Generated reports.
  //
  // SENTIENT's report feature: templates are generated into stored report
  // files, asynchronously. Unrelated to the two dashboard-export methods above,
  // which share the /api/report prefix but not the concept.
  //
  // Every endpoint is authorized server-side against the ReportTemplate
  // resource, and CUSTOMER_USERs are additionally narrowed to their own
  // customer subtree. Callers therefore never need to pre-filter for
  // permissions: the list simply comes back scoped, and an unauthorized
  // caller gets a 403.
  // ---------------------------------------------------------------------------

  /// Page through generated reports, newest first by default.
  ///
  /// [reportTemplateId] narrows to reports produced from one template, and
  /// [userId] to those generated by one user.
  Future<PageData<GeneratedReport>> getReports(PageLink pageLink,
      {String? reportTemplateId,
      String? userId,
      RequestConfig? requestConfig}) async {
    var queryParams = pageLink.toQueryParameters();
    if (reportTemplateId != null) {
      queryParams['reportTemplateId'] = reportTemplateId;
    }
    if (userId != null) {
      queryParams['userId'] = userId;
    }
    var response = await _tbClient.get<Map<String, dynamic>>('/api/reports',
        queryParameters: queryParams,
        options: defaultHttpOptionsFromConfig(requestConfig));
    return _tbClient.compute(parseGeneratedReportPageData, response.data!);
  }

  /// Page through generated reports with the full filter set.
  ///
  /// Prefer this over [getReports] when filtering: only this endpoint supports
  /// a time range. It also returns ids as EntityId objects rather than bare
  /// strings, which [GeneratedReport.fromJson] handles transparently.
  ///
  /// [startTime] and [endTime] are ms since epoch, matched against the
  /// report's creation time.
  Future<PageData<GeneratedReport>> getReportInfos(PageLink pageLink,
      {String? reportTemplateId,
      String? userId,
      int? startTime,
      int? endTime,
      bool? includeCustomers,
      RequestConfig? requestConfig}) async {
    var queryParams = pageLink.toQueryParameters();
    if (reportTemplateId != null) {
      queryParams['reportTemplateId'] = reportTemplateId;
    }
    if (userId != null) {
      queryParams['userId'] = userId;
    }
    if (startTime != null) {
      queryParams['startTime'] = startTime;
    }
    if (endTime != null) {
      queryParams['endTime'] = endTime;
    }
    if (includeCustomers != null) {
      queryParams['includeCustomers'] = includeCustomers;
    }
    var response = await _tbClient.get<Map<String, dynamic>>(
        '/api/v2/reportInfos/all',
        queryParameters: queryParams,
        options: defaultHttpOptionsFromConfig(requestConfig));
    return _tbClient.compute(parseGeneratedReportPageData, response.data!);
  }

  /// Fetch a single report, or null if it no longer exists.
  Future<GeneratedReport?> getReport(String reportId,
      {RequestConfig? requestConfig}) async {
    return nullIfNotFound(
      (RequestConfig requestConfig) async {
        var response = await _tbClient.get<Map<String, dynamic>>(
            '/api/report/$reportId',
            options: defaultHttpOptionsFromConfig(requestConfig));
        return response.data != null
            ? GeneratedReport.fromJson(response.data!)
            : null;
      },
      requestConfig: requestConfig,
    );
  }

  /// Progress of a generation job. Poll this after [generateReport] until
  /// [ReportStatus.isInProgress] goes false.
  Future<ReportGenerationStatus> getReportGenerationStatus(String reportId,
      {RequestConfig? requestConfig}) async {
    var response = await _tbClient.get<Map<String, dynamic>>(
        '/api/report/$reportId/status',
        options: defaultHttpOptionsFromConfig(requestConfig));
    return ReportGenerationStatus.fromJson(response.data!);
  }

  /// Download the generated file as bytes.
  ///
  /// Returns raw bytes rather than a stream because the endpoint requires the
  /// JWT: the URL cannot simply be handed to a browser or download manager.
  /// Only valid once the report reaches [ReportStatus.completed].
  Future<Uint8List> downloadReport(String reportId,
      {ProgressCallback? onReceiveProgress, RequestConfig? requestConfig}) async {
    var options = defaultHttpOptionsFromConfig(requestConfig);
    options.responseType = ResponseType.bytes;
    var response = await _tbClient.get<List<int>>(
        '/api/report/$reportId/download',
        options: options,
        onReceiveProgress: onReceiveProgress);
    return Uint8List.fromList(response.data!);
  }

  /// Start generating a report from a template.
  ///
  /// Returns as soon as the job is queued — the response carries the new
  /// report id with status PENDING, not a finished file.
  Future<GenerateReportResponse> generateReport(GenerateReportRequest request,
      {RequestConfig? requestConfig}) async {
    var response = await _tbClient.post<Map<String, dynamic>>(
        '/api/report/generate',
        data: jsonEncode(request.toJson()),
        options: defaultHttpOptionsFromConfig(requestConfig));
    return GenerateReportResponse.fromJson(response.data!);
  }

  Future<void> deleteReport(String reportId,
      {RequestConfig? requestConfig}) async {
    await _tbClient.delete('/api/report/$reportId',
        options: defaultHttpOptionsFromConfig(requestConfig));
  }

  /// Page through the templates the user is allowed to generate from.
  ///
  /// [formatList] and [typeList] are comma-separated server-side filters,
  /// e.g. 'PDF,CSV' and 'REPORT,SUBREPORT'.
  Future<PageData<ReportTemplateInfo>> getReportTemplateInfos(PageLink pageLink,
      {String? formatList,
      String? typeList,
      RequestConfig? requestConfig}) async {
    var queryParams = pageLink.toQueryParameters();
    if (formatList != null) {
      queryParams['formatList'] = formatList;
    }
    if (typeList != null) {
      queryParams['typeList'] = typeList;
    }
    var response = await _tbClient.get<Map<String, dynamic>>(
        '/api/reportTemplateInfos/all',
        queryParameters: queryParams,
        options: defaultHttpOptionsFromConfig(requestConfig));
    return _tbClient.compute(parseReportTemplateInfoPageData, response.data!);
  }
}
